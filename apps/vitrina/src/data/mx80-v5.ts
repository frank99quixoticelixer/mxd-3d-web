import type { Subsistema } from "@/lib/esquema";

/**
 * Piezas que trajo el GLB v5 (MX80_completo_v5_web.glb) y el catalogo no
 * tenia: aspersor centrifugo, cableado del brazo, bateria, PDB, rieles, radar
 * y luces, bomba, LiDAR, camaras y la tornilleria que faltaba.
 *
 * ESTE ARCHIVO ES IDENTICO EN VITRINA E INTERNA. Cada app lo adapta a su
 * propio esquema en data/mx80.ts (interna agrega camposNoAplican y la carpeta
 * de trazabilidad; vitrina se queda con lo publico al recortar). Un cambio
 * aqui se copia a la otra app.
 *
 * Generado por scripts fuera del repo a partir del GLB crudo; los datos vienen
 * de tres lugares y cada pieza dice cual en `especificaciones.fuente`:
 *   - el usuario (la tabla del aspersor)
 *   - las cotas de la caja envolvente de cada nodo en el GLB
 *   - el nombre del nodo (rosca y largo de la tornilleria)
 * Lo que ninguno de los tres dice queda en null: un dato vacio es honesto, uno
 * inventado llega al proveedor.
 *
 * No pasan por el CSV de especificaciones (contenido/ no esta en el repo): el
 * BOM Excel de interna los toma de aqui hasta que alguien edite su fila.
 */

/**
 * Donde va cada pieza. Cada app la traduce a sus secciones: las piezas del
 * aspersor solo van en los dos brazos que lo llevan (brazo_CW_3 y brazo_CCW_4
 * en el GLB, secciones brazo-cw-2 y brazo-ccw-2).
 */
export type AreaV5 =
  | "brazos"
  | "brazos-aspersion"
  | "frame"
  | "tanque"
  | "frente"
  | "pilas"
  | "tren";

/** Naturaleza de la pieza: decide que campos de la ficha no aplican (interna). */
export type TipoV5 =
  | "conjunto"
  | "sujetador"
  | "electronica"
  | "pieza"
  | "cable"
  | "manguera"
  | "motor";

export interface PiezaV5 {
  sku: string;
  parteDe: string | null;
  slug: string;
  nombre: string;
  descripcion: string;
  subsistema: Subsistema;
  area: AreaV5;
  tipo: TipoV5;
  cantidadPorSeccion: number;
  nombresBlender: string[];
  orden: number;
  categoria: string | null;
  proceso_fabricacion: string | null;
  descripcion_funcional: string | null;
  especificaciones_tecnicas: string[];
  especificaciones: {
    largo_mm?: number;
    ancho_mm?: number;
    alto_mm?: number;
    material?: string;
    proveedor?: string;
    rosca?: string | null;
    longitud_mm?: number;
    numero_tornillos?: number;
    modulo_conectado?: string;
    notas?: string;
    fuente: string[];
  };
  /**
   * Nombre de la pieza en el modelo 3D, sin lado ni numero de instancia. Es el
   * nombre de su carpeta (trazabilidad en interna), para que el 3D, el BOM y
   * las carpetas digan lo mismo.
   */
  carpeta: string | null;
}

